/*
 * ИДЗ 4. Реверс-инжиниринг.
 * Восстановленный исходный код программы "base" (ELF 64-bit).
 *
 * Анализ:
 *   - Программа принимает один аргумент командной строки.
 *   - Аргумент преобразуется функцией atoi() в целое число.
 *   - Если значение равно 1, программа считается «активированной».
 *   - В остальных случаях — «не активирована».
 *
 * Сборка: gcc -o base_restored reconstructed.c
 * Запуск: ./base_restored 1
 */

#include <stdio.h>
#include <stdlib.h>

int main(int argc, char **argv)
{
      int code = 0;

      if (argc > 1)
                code = atoi(argv[1]);

      if (code != 1) {
                puts("Программа не активирована!");
                return -1;
            }

      puts("Программа активирована.");
      return 0;
  }
